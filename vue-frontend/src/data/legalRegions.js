export function findSido(code) {
  return legalRegions.find(region => region.code === code)
}

export function findCity(sidoCode, cityCode) {
  return findSido(sidoCode)?.cities.find(city => city.code === cityCode)
}

export function formatRegionSelection(selection = []) {
  if (selection.some(item => item.scope === 'ALL')) return '전체 구역'
  return selection.map(item => {
    const sido = findSido(item.sido)
    if (!sido) return ''
    if (item.si === null) return sido.name
    const city = findCity(item.sido, item.si)
    return city ? `${sido.name} ${city.name}` : ''
  }).filter(Boolean).join(', ')
}
